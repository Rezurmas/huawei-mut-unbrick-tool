MULTICAST_IP        = "224.0.0.119"
MULTICAST_PORT      = 13456          # 0x3490
PACKET_SIZE         = 1086
CHUNK_SIZE          = 1024           # 0x400
HEADER_SIZE         = 62             # 1086 - 1024
DEFAULT_INTERVAL_MS = 200

OPCODE_DATA = 1                      # data chunk (1024 bytes)
OPCODE_LAST = 2                      # last chunk (< 1024 bytes)
OPCODE_INIT = 4                      # init/partition table

# Control word values (per sub_4202F0)
CTRL_DATA = (OPCODE_DATA << 29) | 0x00000400  # 0x20000400
CTRL_LAST = (OPCODE_LAST << 29) | 0x00000400  # 0x40000400
CTRL_INIT = (OPCODE_INIT << 29) | 0x00000400  # 0x80000400

# Default INI fields (z generate_ini_file.py + generate_ini_force_cfe.py)
DEFAULT_PACKAGE_ID       = "fnt-HGW"
DEFAULT_PRODUCT_ID       = "fnt-HGW"
DEFAULT_FIRMWARE_VERSION = "0"
DEFAULT_PCB_VERSION      = "0"
PARTITIONS_NORMAL    = "CFE,0x00000000-0x0000FFFF,uncover|kernelfs,0x00010000-0x003FFFFF,cover"
PARTITIONS_FORCE_CFE = "CFE,0x00000000-0x0000FFFF,cover|kernelfs,0x00010000-0x003FFFFF,cover"



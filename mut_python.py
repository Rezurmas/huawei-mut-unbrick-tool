# Packet builder (replika sub_4202F0)
# ============================================================================
def build_packet(opcode: int,
                 chunk_data: bytes,
                 chunk_counter: int,
                 total_size: int,
                 firmware_crc: int,
                 package_id: str,
                 product_id: str,
                 pcb_word: int = 0) -> bytes:
    """
    Buduje 1086-bajtowy packet zgodnie z sub_4202F0.

    Args:
        opcode:        OPCODE_DATA=1, OPCODE_LAST=2, OPCODE_INIT=4
        chunk_data:    do 1024 bajtów payload (zostanie null-padded)
        chunk_counter: sequence number (dword_45E1BC)
        total_size:    całkowity rozmiar pliku firmware
        firmware_crc:  FIRMWARE_CRC_SUM z .ini (CRC całego pliku)
        package_id:    z INI (max 20 bajtów po obcięciu)
        product_id:    z INI (max 20 bajtów po obcięciu)
        pcb_word:      WORD na offset 40-41 (z byte_46568E[4166])
    """
    if len(chunk_data) > CHUNK_SIZE:
        raise ValueError(f"chunk_data too long: {len(chunk_data)} > {CHUNK_SIZE}")

    # Pad chunk to 1024 bytes
    chunk_padded = chunk_data + b'\x00' * (CHUNK_SIZE - len(chunk_data))

    # CRC32 zawsze na 1024 bajtach (per sub_4202F0: sub_420480(&Destination[42], 1024))
    chunk_crc = crc32(chunk_padded)

    # Control word: opcode<<29 | 0x0400
    control_word = (opcode << 29) | 0x00000400

    # PACKAGE_ID padding (20 bytes)
    pkg_bytes = package_id.encode('ascii', errors='replace')[:20]
    pkg_padded = pkg_bytes + b'\x00' * (20 - len(pkg_bytes))

    # PRODUCT_ID padding (20 bytes)
    prod_bytes = product_id.encode('ascii', errors='replace')[:20]
    prod_padded = prod_bytes + b'\x00' * (20 - len(prod_bytes))

    # Header (62 bytes)
    header = struct.pack('<I', control_word)          # [0..3]
    header += struct.pack('<I', chunk_counter)        # [4..7]
    header += struct.pack('<I', chunk_crc)            # [8..11]
    header += struct.pack('<I', total_size)           # [12..15]
    header += struct.pack('<I', firmware_crc)         # [16..19]
    header += pkg_padded                               # [20..39]
    header += struct.pack('<H', pcb_word & 0xFFFF)    # [40..41]
    header += prod_padded                              # [42..61]

    assert len(header) == HEADER_SIZE, f"Header size {len(header)} != {HEADER_SIZE}"

    packet = header + chunk_padded
    assert len(packet) == PACKET_SIZE, f"Packet size {len(packet)} != {PACKET_SIZE}"

    return packet


def build_init_payload(partitions: list) -> bytes:
    """
    Buduje 1024-byte payload dla INIT packet (opcode 4).
    Format z sub_41F2F0 partition loop:
        for each partition:
            qmemcpy(v5 - 5, v6, 0x14);   // 20 bytes (name+meta?)
            *v5 = start_offset            // 4 bytes
            v5[1] = end_offset            // 4 bytes
            *(BYTE*)(v5+2) = cover ? 2 : 1  // 1 byte (uncover=1, cover=2)
            v5 += 8 dword (= 32 bytes)    // padding 3 bytes
    """
    payload = b''
    for p in partitions:
        # Name (20 bytes, null-padded)
        name_bytes = p['name'].encode('ascii', errors='replace')[:20]
        name_padded = name_bytes + b'\x00' * (20 - len(name_bytes))
        payload += name_padded
        # Start, End offsets
        payload += struct.pack('<II', p['start'] & 0xFFFFFFFF, p['end'] & 0xFFFFFFFF)
        # Cover flag (cover=2, uncover=1)
        payload += b'\x02' if p['cover'] else b'\x01'
        # Padding (3 bytes to reach 32-byte total per partition)
        payload += b'\x00\x00\x00'
    return payload



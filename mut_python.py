#!/usr/bin/env python3
"""
mut_python.py - Python replika HuaweiMUT.exe (WS7200/AX3/Honor Router 3)

Reverse-engineered z HuaweiMUT.exe (389120 bytes, VC7-14 MFC, multicast UDP).
Funkcje zreversowane (IDA Pro + Hex-Rays):
    sub_402260  - OnButtonStart() handler (UI)
    sub_41FD40  - INI parser + INI_CRC_SUM check (sets dword_460E24)
    sub_41F2F0  - main send loop (UDP multicast)
    sub_4202F0  - packet builder (1086 bytes: 62 header + 1024 data)
    sub_41F0A0  - socket setup
    sub_41F8E0  - firmware CRC32 calculator (zlib-compatible)
    sub_420480  - CRC32 (zlib)
    sub_41F6D0  - adapter IP lookup (GetAdaptersInfo)
    sub_41F820  - precise sleep (QueryPerformanceCounter)
    sub_41F960  - file chunk read (fseek+fread)

PACKET FORMAT (1086 bytes):
    [0..3]    4   control_word    = (opcode << 29) | 0x00000400
                                    DATA = 0x20000400
                                    LAST = 0x40000400
                                    INIT = 0x80000400
    [4..7]    4   chunk_counter   sequence (uint32 LE)
    [8..11]   4   chunk_crc32     CRC32 of (padded to 1024) chunk
    [12..15]  4   total_file_size uint32 LE
    [16..19]  4   firmware_crc32  FIRMWARE_CRC_SUM (z INI)
    [20..39]  20  PACKAGE_ID      ASCII, null-padded
    [40..41]  2   unknown_word    (z byte_46568E[4166])
    [42..61]  20  PRODUCT_ID      ASCII, null-padded
    [62..1085] 1024 chunk_data    firmware chunk, null-padded if shorter

SOCKET CONFIG (sub_41F0A0):
    socket(AF_INET, SOCK_DGRAM, 0)
    SO_BROADCAST = 1
    bind(PC_IP, 13456)              <- SOURCE PORT = 13456!
    IP_ADD_MEMBERSHIP(224.0.0.119, PC_IF)
    IP_MULTICAST_LOOP = 1
    IP_MULTICAST_TTL = 0            <- local network ONLY
    IP_MULTICAST_IF = PC_IP
"""


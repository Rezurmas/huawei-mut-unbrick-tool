def list_network_adapters() -> list:
    """Lista kart sieciowych Windows z IPv4. Returns [{name, ip, is_wifi}, ...]."""
    adapters = []
    try:
        result = subprocess.run(['ipconfig'], capture_output=True, text=True,
                                encoding='cp852', errors='replace', timeout=5)
        current = None
        for line in result.stdout.splitlines():
            # Header karty (linia nie zaczyna sie spacja i kończy ':')
            if line and not line.startswith(' ') and not line.startswith('\t') and line.rstrip().endswith(':'):
                current = line.strip().rstrip(':').strip()
            elif 'IPv4' in line and ':' in line:
                ip = line.split(':', 1)[1].strip()
                ip = ip.replace('(Preferred)', '').replace('(Preferowane)', '').strip()
                if ip and current and not ip.startswith('169.254.'):
                    is_wifi = bool(
                        'wireless' in current.lower()
                        or 'wi-fi' in current.lower()
                        or 'wifi' in current.lower()
                        or 'bezprzewod' in current.lower()
                    )
                    adapters.append({'name': current, 'ip': ip, 'is_wifi': is_wifi})
    except Exception as e:
        print(f"[WARN] ipconfig failed: {e}", file=sys.stderr)

    # Fallback: gethostbyname_ex
    if not adapters:
        try:
            _, _, ips = socket.gethostbyname_ex(socket.gethostname())
            for ip in ips:
                if not ip.startswith('127.') and not ip.startswith('169.254.'):
                    adapters.append({'name': 'host', 'ip': ip, 'is_wifi': False})
        except Exception:
            pass
    return adapters


def adapter_for_ip(ip: str) -> dict:
    """Zwraca info o adapterze dla danego IP, lub None."""
    for a in list_network_adapters():
        if a['ip'] == ip:
            return a
    return None


def router_is_alive(ip: str = '192.168.1.1', timeout_ms: int = 1000) -> bool:
    """Ping na router. True = router odpowiada (PROBLEM dla unbrick'a!)."""
    try:
        result = subprocess.run(
            ['ping', '-n', '1', '-w', str(timeout_ms), ip],
            capture_output=True, text=True, timeout=timeout_ms / 1000.0 + 2
        )
        return result.returncode == 0 and ('TTL=' in result.stdout or 'ttl=' in result.stdout)
    except Exception:
        return False


def auto_detect_pc_ip(prefer: str = '192.168.1.') -> str:
    """Znajdz IP karty - preferuj 192.168.1.x, potem 192.168.x.x, potem cokolwiek."""
    adapters = list_network_adapters()
    for a in adapters:
        if a['ip'].startswith(prefer):
            return a['ip']
    for a in adapters:
        if a['ip'].startswith('192.168.'):
            return a['ip']
    for a in adapters:
        if not a['ip'].startswith('127.'):
            return a['ip']
    return None


def validate_pc_ip(pc_ip: str) -> bool:
    """Sprawdź czy pc_ip istnieje na ktorymkolwiek adapterze."""
    if not pc_ip:
        return False
    return any(a['ip'] == pc_ip for a in list_network_adapters())


def precise_sleep(ms: int) -> None:
    """Replika sub_41F820 (QueryPerformanceCounter busy-wait)."""
    if ms <= 0:
        return
    target = time.perf_counter() + ms / 1000.0
    while time.perf_counter() < target:
        if ms >= 100:
            time.sleep(0.001)


def parse_ini(ini_path: Path) -> dict:
    """Parsuje INI w stylu sub_41FD40 (key=value, ignore comments)."""
    fields = {}
    with open(ini_path, 'rb') as f:
        content = f.read()
    # Both \r\n and \n line endings (sub_41FD40 czyta jako binary)
    for raw_line in content.replace(b'\r\n', b'\n').split(b'\n'):
        line = raw_line.strip()
        if not line or line.startswith(b'#') or line.startswith(b'//'):
            continue
        if b'=' not in line:
            continue
        key, _, val = line.partition(b'=')
        fields[key.decode('ascii', errors='replace').strip()] = val.decode('ascii', errors='replace').strip()
    return fields


def parse_partitions(partitions_str: str) -> list:
    """Parsuje 'CFE,0x0-0xFFFF,uncover|kernelfs,0x10000-0x3FFFFF,cover'."""
    partitions = []
    if not partitions_str:
        return partitions
    for entry in partitions_str.split('|'):
        parts = entry.split(',')
        if len(parts) < 3:
            continue
        name = parts[0]
        range_str = parts[1]
        flag = parts[2]
        if '-' not in range_str:
            continue
        start_str, end_str = range_str.split('-', 1)
        try:
            start = int(start_str, 16) if start_str.startswith('0x') else int(start_str)
            end = int(end_str, 16) if end_str.startswith('0x') else int(end_str)
        except ValueError:
            continue
        partitions.append({
            'name': name,
            'start': start,
            'end': end,
            'flag': flag,
            'cover': flag.lower() == 'cover',
        })
    return partitions



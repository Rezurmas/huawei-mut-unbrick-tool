def crc32(data: bytes) -> int:
    """Identycznie jak sub_420480 (potwierdzone - generate_ini_file.py używa zlib i działa)."""
    return zlib.crc32(data) & 0xFFFFFFFF


# ============================================================================
# INI Generation (skopiowane z generate_ini_file.py + generate_ini_force_cfe.py;
# tamte pliki POZOSTAJĄ NIETKNIĘTE - to kopia inline dla all-in-one tool)
# ============================================================================
def process_firmware_file(file_path: str):
    """Returns (file_size, file_crc32). Identyczne z generate_ini_file.py."""
    with open(file_path, 'rb') as f:
        data = f.read()
    return len(data), crc32(data)


def generate_ini_content(filename: str, filesize: int, firmware_crc: int,
                         force_cfe: bool = False,
                         package_id: str = DEFAULT_PACKAGE_ID,
                         product_id: str = DEFAULT_PRODUCT_ID,
                         firmware_version: str = DEFAULT_FIRMWARE_VERSION,
                         pcb_version: str = DEFAULT_PCB_VERSION) -> str:
    """Generuje content INI z poprawnym INI_CRC_SUM (zlib CRC32)."""
    partitions = PARTITIONS_FORCE_CFE if force_cfe else PARTITIONS_NORMAL
    content = (
        "# autogenerated by tools\n"
        "# do NOT modify this file\n"
        f"IMAGE_NAME={filename}\n"
        f"IMAGE_SIZE={filesize}\n"
        f"PACKAGE_ID={package_id}\n"
        f"PRODUCT_ID={product_id}\n"
        f"FIRMWARE_VERSION={firmware_version}\n"
        f"PCB_VERSION={pcb_version}\n"
        f"FIRMWARE_CRC_SUM={firmware_crc}\n"
        f"PARTITIONS={partitions}\n"
        "INI_CRC_SUM="
    )
    ini_crc = crc32(content.encode('ascii'))
    content += str(ini_crc)
    return content


def generate_ini_for_firmware(firmware_path: str, force_cfe: bool = False,
                              ini_path: str = None, backup: bool = True) -> str:
    """Stwórz .ini obok firmware'u. Zwraca path do .ini."""
    filename = os.path.basename(firmware_path)
    folder = os.path.dirname(firmware_path) or '.'
    base = os.path.splitext(filename)[0]
    if ini_path is None:
        ini_path = os.path.join(folder, f"{base}.ini")

    filesize, fw_crc = process_firmware_file(firmware_path)

    if backup and os.path.isfile(ini_path):
        bak = ini_path + ".bak"
        if not os.path.isfile(bak):
            shutil.copy2(ini_path, bak)
            print(f"[INI] Backup oryginalu: {os.path.basename(bak)}")

    content = generate_ini_content(filename, filesize, fw_crc, force_cfe=force_cfe)
    with open(ini_path, 'w', newline='\n', encoding='ascii') as f:
        f.write(content)

    mode = "FORCE-CFE (CFE+kernelfs cover)" if force_cfe else "normalny (CFE uncover)"
    print(f"[INI] Wygenerowano [{mode}]: {ini_path}")
    print(f"      Size:    {filesize:,} bytes")
    print(f"      CRC32:   {fw_crc} (0x{fw_crc:08X})")
    return ini_path



class MUT:
    def __init__(self,
                 firmware_path: str,
                 ini_path: str,
                 pc_ip: str,
                 dest_ip: str = MULTICAST_IP,
                 port: int = MULTICAST_PORT,
                 interval_ms: int = DEFAULT_INTERVAL_MS,
                 use_multicast: bool = True,
                 ttl: int = 0,
                 verbose: bool = False,
                 log_hex: bool = False,
                 listen: bool = False,
                 max_passes: int = 0):
        self.firmware_path = firmware_path
        self.ini_path = ini_path
        self.pc_ip = pc_ip
        self.dest_ip = dest_ip
        self.port = port
        self.interval_ms = interval_ms
        self.use_multicast = use_multicast
        self.ttl = ttl
        self.verbose = verbose
        self.log_hex = log_hex
        self.listen = listen
        self.max_passes = max_passes

        # Load INI
        self.fields = parse_ini(Path(ini_path))
        self.package_id = self.fields.get('PACKAGE_ID', '')
        self.product_id = self.fields.get('PRODUCT_ID', '')
        self.partitions = parse_partitions(self.fields.get('PARTITIONS', ''))

        # Validate required fields
        required = ['IMAGE_NAME', 'IMAGE_SIZE', 'PACKAGE_ID', 'PRODUCT_ID',
                    'FIRMWARE_VERSION', 'PCB_VERSION', 'FIRMWARE_CRC_SUM',
                    'INI_CRC_SUM', 'PARTITIONS']
        missing = [k for k in required if not self.fields.get(k)]
        if missing:
            print(f"[WARN] Missing INI fields: {missing}", file=sys.stderr)

        # Load firmware
        with open(firmware_path, 'rb') as f:
            self.firmware_data = f.read()
        self.file_size = len(self.firmware_data)
        self.firmware_crc = crc32(self.firmware_data)

        # Verify CRC matches INI
        ini_fw_crc = int(self.fields.get('FIRMWARE_CRC_SUM', '0'))
        if ini_fw_crc != self.firmware_crc:
            print(f"[WARN] Firmware CRC mismatch! Calc={self.firmware_crc} INI={ini_fw_crc}", file=sys.stderr)

        # Stats
        self.passes_completed = 0
        self.packets_sent = 0
        self.bytes_sent = 0
        self.running = False
        self.responses = []

    def setup_socket(self) -> socket.socket:
        """Replika sub_41F0A0. Bind robust dla WinError 10049."""
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM, 0)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        # Bind source port = 13456 (per sub_41F0A0)
        # Defensive: jezeli pc_ip nie istnieje na karcie -> fallback na 0.0.0.0
        bind_ip = self.pc_ip
        try:
            s.bind((bind_ip, self.port))
        except OSError as e:
            if e.winerror == 10049 if hasattr(e, 'winerror') else False:
                print(f"[WARN] IP {self.pc_ip} nie istnieje na karcie - bind 0.0.0.0:{self.port}", file=sys.stderr)
            else:
                print(f"[WARN] bind({bind_ip}:{self.port}) failed: {e} - retry 0.0.0.0", file=sys.stderr)
            s.bind(('0.0.0.0', self.port))

        if self.use_multicast:
            # IP_ADD_MEMBERSHIP
            mreq = socket.inet_aton(self.dest_ip) + socket.inet_aton(self.pc_ip)
            try:
                s.setsockopt(socket.IPPROTO_IP, socket.IP_ADD_MEMBERSHIP, mreq)
            except OSError as e:
                print(f"[WARN] IP_ADD_MEMBERSHIP failed: {e}", file=sys.stderr)
            # IP_MULTICAST_LOOP = 1
            s.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_LOOP, 1)
            # IP_MULTICAST_TTL (default 0 = local only, per MUT)
            s.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_TTL, self.ttl)
            # IP_MULTICAST_IF = PC interface
            s.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_IF, socket.inet_aton(self.pc_ip))

        s.settimeout(0.001)  # for non-blocking recv
        return s

    def listen_thread(self, sock: socket.socket):
        """Listen for router responses on the same socket."""
        print("[LISTEN] Starting response listener...")
        while self.running:
            try:
                data, addr = sock.recvfrom(4096)
                self.responses.append((time.time(), addr, data))
                print(f"\n[*** RESPONSE FROM ROUTER ***] {addr} ({len(data)} bytes)")
                print(f"  Hex: {data[:64].hex()}{'...' if len(data) > 64 else ''}")
            except socket.timeout:
                continue
            except OSError:
                break

    def send_loop(self):
        """Main send loop per sub_41F2F0."""
        sock = self.setup_socket()
        dest = (self.dest_ip, self.port)

        self.running = True

        if self.listen:
            listener = threading.Thread(target=self.listen_thread, args=(sock,), daemon=True)
            listener.start()

        try:
            while self.running:
                self._send_one_pass(sock, dest)
                self.passes_completed += 1
                print(f"\n=== PASS {self.passes_completed} COMPLETE ({self.packets_sent} pkts, "
                      f"{self.bytes_sent/1024/1024:.2f} MB sent so far) ===\n")
                if self.max_passes and self.passes_completed >= self.max_passes:
                    print(f"Reached max_passes={self.max_passes}, stopping.")
                    break
                precise_sleep(self.interval_ms * 2)
        except KeyboardInterrupt:
            print("\n[CTRL+C] Stopping...")
        finally:
            self.running = False
            sock.close()

    def _send_one_pass(self, sock, dest):
        """Single pass: INIT + DATA*N + LAST."""
        chunk_counter = 0

        # 1. INIT packet (opcode 4) with partition table
        init_payload = build_init_payload(self.partitions)
        init_packet = build_packet(
            opcode=OPCODE_INIT,
            chunk_data=init_payload,
            chunk_counter=chunk_counter,
            total_size=self.file_size,
            firmware_crc=self.firmware_crc,
            package_id=self.package_id,
            product_id=self.product_id,
        )
        self._send_packet(sock, init_packet, dest, 'INIT', chunk_counter, 0)
        chunk_counter += 1
        precise_sleep(self.interval_ms)

        if not self.running:
            return

        # 2. DATA + LAST packets
        offset = 0
        while offset < self.file_size and self.running:
            remaining = self.file_size - offset
            if remaining <= CHUNK_SIZE:
                # LAST packet (opcode 2)
                chunk_data = self.firmware_data[offset:offset + remaining]
                packet = build_packet(
                    opcode=OPCODE_LAST,
                    chunk_data=chunk_data,
                    chunk_counter=chunk_counter,
                    total_size=self.file_size,
                    firmware_crc=self.firmware_crc,
                    package_id=self.package_id,
                    product_id=self.product_id,
                )
                self._send_packet(sock, packet, dest, 'LAST', chunk_counter, offset)
                break
            else:
                # DATA packet (opcode 1)
                chunk_data = self.firmware_data[offset:offset + CHUNK_SIZE]
                packet = build_packet(
                    opcode=OPCODE_DATA,
                    chunk_data=chunk_data,
                    chunk_counter=chunk_counter,
                    total_size=self.file_size,
                    firmware_crc=self.firmware_crc,
                    package_id=self.package_id,
                    product_id=self.product_id,
                )
                self._send_packet(sock, packet, dest, 'DATA', chunk_counter, offset)
                offset += CHUNK_SIZE
                chunk_counter += 1
                precise_sleep(self.interval_ms)

    def _send_packet(self, sock, packet, dest, label, seq, offset):
        try:
            sent = sock.sendto(packet, dest)
            self.packets_sent += 1
            self.bytes_sent += sent
            if self.verbose:
                pct = (offset / self.file_size * 100) if self.file_size else 0
                print(f"[#{self.packets_sent:6d}] {label:4s} seq={seq:6d} "
                      f"off={offset:8d}/{self.file_size} ({pct:5.1f}%)")
            if self.log_hex:
                print(f"  Header: {packet[:HEADER_SIZE].hex()}")
        except OSError as e:
            print(f"[ERROR] sendto failed: {e}", file=sys.stderr)
            self.running = False


